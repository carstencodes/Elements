    [DisplayName("Generated writable paths match ConfigurationBinder behavior")]
    [Description(
        "Verifies that the generated writable configuration paths correspond accurately with properties bound by Microsoft.Extensions.Configuration.Binder.")]
    public async Task GeneratedWritablePathsMatchConfigurationBinderBehavior()
    {
        GeneratorRun run = RunGenerator(Input.BindingScenario, "BindingScenario.Settings.Attributes");
        System.Reflection.Assembly assembly = System.Reflection.Assembly.Load(run.AssemblyImage);
        Type rootType = assembly.GetType("BindingScenario.Settings.Root")!;
        Type contextType = assembly.GetType("BindingScenario.Settings.ConfigurationContextOfRoot")!;
        object root = Activator.CreateInstance(rootType)!;

        Dictionary<string, string?> values = new(StringComparer.Ordinal)
        {
            [$"renamed:{nameof(TestChildModel.Name)}"] = "bound child",
            [nameof(TestRootModel.ReadOnlyName)] = "ignored string",
            [nameof(TestRootModel.ReadOnlyScore)] = "42",
            [nameof(TestRootModel.NullableName)] = "bound nullable",
            [nameof(TestRootModel.NullableScore)] = "7",
        };
        IConfigurationRoot configuration = new ConfigurationBuilder()
            .AddInMemoryCollection(values)
            .Build();
        ConfigurationBinder.Bind(configuration, root);

        IReadOnlySet<ConfigurationPath> writablePaths =
            ToConfigurationPaths(contextType
                .GetMethod(nameof(ConfigurationObjectContextBase<object>.GetWritableConfigurationPaths))!
                .Invoke(Activator.CreateInstance(contextType, nonPublic: true), null)!);
        HashSet<string> generatedPaths = writablePaths
            .Select(static path => path.ToString())
            .ToHashSet(StringComparer.Ordinal);
        object child = rootType.GetProperty(nameof(TestRootModel.Child))!.GetValue(root)!;
        Dictionary<string, bool> binderResults = new(StringComparer.Ordinal)
        {
            [$"renamed:{nameof(TestChildModel.Name)}"] =
                Equals(child.GetType().GetProperty(nameof(TestChildModel.Name))!.GetValue(child), "bound child"),
            [nameof(TestRootModel.ReadOnlyName)] =
                !Equals(rootType.GetProperty(nameof(TestRootModel.ReadOnlyName))!.GetValue(root), "read-only"),
            [nameof(TestRootModel.ReadOnlyScore)] =
                !Equals(rootType.GetProperty(nameof(TestRootModel.ReadOnlyScore))!.GetValue(root), 9),
            [nameof(TestRootModel.NullableName)] =
                Equals(rootType.GetProperty(nameof(TestRootModel.NullableName))!.GetValue(root), "bound nullable"),
            [nameof(TestRootModel.NullableScore)] =
                Equals(rootType.GetProperty(nameof(TestRootModel.NullableScore))!.GetValue(root), 7),
        };

        using (Assert.Multiple())
        {
            foreach ((string path, bool binderAccepted) in binderResults)
            {
                await Assert.That(generatedPaths.Contains(path))
                    .IsEqualTo(binderAccepted)
                    .Because(
                        $"generated writable path '{path}' presence should match ConfigurationBinder behavior ({binderAccepted})");
            }
        }
    }

