    private static void CollectTypePaths(
        ITypeSymbol type,
        ImmutableArray<string> prefix,
        ContextPaths paths,
        INamedTypeSymbol rootType,
        bool isWritable,
        ISet<INamedTypeSymbol> activeTypes)
    {
