        return string.Concat("ConfigurationContext_", hint, "_", hash, ".g.cs");
    }

    /// <summary>Creates a compact deterministic suffix for file names whose readable portions may collide.</summary>
    /// <param name="value">The fully qualified value to hash.</param>
    /// <param name="bytes">The number of leading digest bytes to retain.</param>
    /// <returns>The requested digest prefix encoded as uppercase hexadecimal.</returns>
    private static string CreateHashSuffix(string value, int bytes)
    {
        using SHA256 algorithm = SHA256.Create();
        byte[] hash = algorithm.ComputeHash(Encoding.UTF8.GetBytes(value));
        return BitConverter.ToString(hash, 0, bytes).Replace("-", string.Empty);
    }

