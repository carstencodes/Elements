    /// <summary>
    /// Finds context-backed model types, unwrapping arrays, nullable values, and collections.
    /// </summary>
    /// <param name="type">The property's static type.</param>
    /// <returns>Nested model types whose generated contexts can be linked from the property's documentation.</returns>
    private static IEnumerable<INamedTypeSymbol> GetContextModels(ITypeSymbol type)
    {
        if (type is IArrayTypeSymbol arrayType)
        {
            return GetContextModels(arrayType.ElementType);
        }

        if (type is not INamedTypeSymbol namedType)
        {
            return [];
        }

        if (namedType.OriginalDefinition.SpecialType == SpecialType.System_Nullable_T)
        {
            return GetContextModels(namedType.TypeArguments[0]);
        }

        if (ConfigurationPathGenerator.IsSimpleType(namedType))
        {
            return [];
        }

        if (ConfigurationPathGenerator.TryGetCollectionValues(namedType, out ImmutableArray<ITypeSymbol> values))
        {
            return values.SelectMany(GetContextModels).ToArray();
        }

        return [namedType];
    }

    /// <summary>
    /// Declares reusable context instances for nested models that may be visited during a dump.
    /// </summary>
    /// <param name="source">The source buffer receiving generated field declarations.</param>
    /// <param name="type">The root model whose reachable properties are traversed.</param>
    private static void AppendNestedContextFields(StringBuilder source, INamedTypeSymbol type)
    {
        HashSet<INamedTypeSymbol> models = new(SymbolEqualityComparer.Default);
        HashSet<INamedTypeSymbol> visited = new(SymbolEqualityComparer.Default);
        foreach (IPropertySymbol property in ConfigurationPathGenerator.GetBindableProperties(type))
