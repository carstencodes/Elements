            source.Append("    private static readonly ")
                .Append(ConfigurationDumpMethodEmitter.CreateContextReference(model))
                .Append(' ')
                .Append(ConfigurationDumpMethodEmitter.CreateContextFieldName(model))
                .AppendLine(" = new();");
        }

        if (models.Count > 0)
        {
            source.AppendLine();
        }
    }

    /// <summary>
    /// Collects nested model contexts while stopping recursion at model definitions already visited.
    /// </summary>
    /// <param name="type">The current property, collection element, or nested model type.</param>
    /// <param name="models">The nested types requiring cached contexts.</param>
    /// <param name="visited">The model definitions already traversed through their properties.</param>
    private static void CollectNestedContextModels(
        ITypeSymbol type,
        ISet<INamedTypeSymbol> models,
        ISet<INamedTypeSymbol> visited)
    {
        if (type is IArrayTypeSymbol arrayType)
        {
            CollectNestedContextModels(arrayType.ElementType, models, visited);
            return;
        }

        if (type is not INamedTypeSymbol namedType)
        {
            return;
        }

        if (namedType.OriginalDefinition.SpecialType == SpecialType.System_Nullable_T)
        {
            CollectNestedContextModels(namedType.TypeArguments[0], models, visited);
            return;
        }

        if (ConfigurationPathGenerator.IsSimpleType(namedType))
        {
            return;
        }

        if (ConfigurationPathGenerator.TryGetCollectionValues(namedType, out ImmutableArray<ITypeSymbol> values))
        {
            foreach (ITypeSymbol value in values)
