    /// <summary>Creates a stable source hint name that remains unique for similarly sanitized type names.</summary>
    /// <param name="type">The model type represented by the generated source.</param>
    /// <returns>A deterministic <c>.g.cs</c> file name for Roslyn's generated-source output.</returns>
    internal static string CreateHintName(INamedTypeSymbol type)
    {
        string symbolName = type.ToDisplayString(FullyQualifiedFormat);
        StringBuilder hint = new(symbolName.Length);
        foreach (char character in symbolName)
        {
            hint.Append(char.IsLetterOrDigit(character) ? character : '_');
