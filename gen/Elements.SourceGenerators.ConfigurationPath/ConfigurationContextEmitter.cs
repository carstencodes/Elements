        // Add before recursing so self-referencing models produce one field rather than infinite discovery.
        if (!visited.Add(namedType.OriginalDefinition))
        {
            return;
        }

        foreach (IPropertySymbol property in ConfigurationPathGenerator.GetBindableProperties(namedType))
        {
            CollectNestedContextModels(property.Type, models, visited);
        }
    }

    /// <summary>Collects readable and writable property paths reachable from the root model.</summary>
    /// <param name="rootType">The model represented by the context being emitted.</param>
    /// <returns>Both path sets, kept separate because readable metadata is broader than writable metadata.</returns>
    private static ContextPaths CollectPaths(INamedTypeSymbol rootType)
    {
        ContextPaths paths = new();
        HashSet<INamedTypeSymbol> activeTypes = new(SymbolEqualityComparer.Default)
        {
            rootType.OriginalDefinition,
